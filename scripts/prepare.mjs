import { writeFile } from 'node:fs/promises';
import { loadListings } from '../src/data.ts';

const listings = await loadListings();
if (!listings.length) throw new Error('No listings found. Restore the curated inventory before building.');
await writeFile('src/listing-ids.mjs', `// Generated by npm run build from the reviewed inventory.\nexport const listingIds = new Set(${JSON.stringify(listings.map(l => l.id))});\n`);
